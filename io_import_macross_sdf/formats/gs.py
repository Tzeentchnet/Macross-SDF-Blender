def addr32(w: int, h: int, bw: int) -> np.ndarray:
    """Byte address of every PSMCT32 pixel of a w x h rect, buffer width bw (x64 px)."""
    y, x = np.mgrid[0:h, 0:w]
    page = (y // 32) * bw + (x // 64)
    block = BLOCK32[(y % 32) // 8, (x % 64) // 8]
    word = COLUMN32[y % 8, x % 8]
    return (page * 8192 + block * 256 + word * 4)


def addr8(w: int, h: int, bw: int) -> np.ndarray:
    """Byte address of every PSMT8 texel. bw in 64-texel units (pages are 128 wide)."""
    y, x = np.mgrid[0:h, 0:w]
    pages_per_row = max(1, bw // 2)
    page = (y // 64) * pages_per_row + (x // 128)
    block = BLOCK8[(y % 64) // 16, (x % 128) // 16]
    return page * 8192 + block * 256 + COLUMN8[y % 16, x % 16]


def addr4(w: int, h: int, bw: int) -> np.ndarray:
    """Nibble address of every PSMT4 texel. bw in 64-texel units (pages are 128 wide)."""
    y, x = np.mgrid[0:h, 0:w]
    pages_per_row = max(1, bw // 2)
    page = (y // 128) * pages_per_row + (x // 128)
    block = BLOCK4[(y % 128) // 16, (x % 128) // 32]
    return page * 16384 + block * 512 + COLUMN4[y % 16, x % 32]


def unswizzle(data: bytes, w: int, h: int, bpp: int, mode: str = "auto") -> np.ndarray:
    """Return linear palette indices (h*w,) for swizzled 4/8-bit image bytes.

    The file stores a PSMCT32 rectangle in raster order.  We place it into
    a virtual GS memory and read it back with the indexed format.
    """
    nbytes = w * h * bpp // 8
    src = np.frombuffer(data, np.uint8, nbytes)
    bw = max(2, w // 64)
    # rectangle size as uploaded in PSMCT32 pixels
    if bpp == 8:
        w32, h32 = max(1, w // 2), max(1, h // 2)
    else:
        w32, h32 = max(1, w // 2), max(1, h // 4)
    if w32 * h32 * 4 != nbytes:
        return None
    bw32 = max(1, w32 // 64) if mode == "auto" else int(mode)
    a32 = addr32(w32, h32, bw32).reshape(-1)
    size = int(max(a32.max() + 4, 1))
    if bpp == 8:
        a = addr8(w, h, bw).reshape(-1)
        size = max(size, int(a.max()) + 1)
        mem = np.zeros(size, np.uint8)
        words = src.reshape(-1, 4)
        for k in range(4):
            mem[a32 + k] = words[:, k]
        return mem[a]
    a = addr4(w, h, bw).reshape(-1)
    size = max(size, int(a.max() // 2) + 1)
    mem = np.zeros(size, np.uint8)
    words = src.reshape(-1, 4)
    for k in range(4):
        mem[a32 + k] = words[:, k]
    byte = mem[a >> 1]
    return np.where(a & 1, byte >> 4, byte & 0x0F).astype(np.uint8)
